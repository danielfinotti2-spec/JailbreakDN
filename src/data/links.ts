/** Recursos por subcategoria, calculado uma vez. */
export const POR_SUBCATEGORIA: Map<string, Resource[]> = (() => {
  const m = new Map<string, Resource[]>();
  for (const r of RESOURCES) {
    const lista = m.get(r.subcategoriaId);
    if (lista) lista.push(r);
    else m.set(r.subcategoriaId, [r]);
  }
  return m;
})();

export const recursosDaSubcategoria = (id: string): Resource[] => POR_SUBCATEGORIA.get(id) ?? [];

/** Recursos de um grupo inteiro (todas as suas subcategorias). */
export const recursosDoGrupo = (subcategoriasDoGrupo: string[]): Resource[] =>
  subcategoriasDoGrupo.flatMap((id) => recursosDaSubcategoria(id));

export const recursoPorId = (id: string): Resource | undefined =>
  RESOURCES.find((r) => r.id === id);

/** Contagem por disponibilidade, para as legendas dos filtros. */
export const POR_DISPONIBILIDADE: Map<string, number> = (() => {
  const m = new Map<string, number>();
  for (const r of RESOURCES) m.set(r.disponibilidade, (m.get(r.disponibilidade) ?? 0) + 1);
  return m;
})();

/** Todas as tags, ordenadas por frequência e depois alfabeticamente. */
export const TODAS_AS_TAGS: { tag: string; total: number }[] = (() => {
  const mapa = new Map<string, number>();
  for (const r of RESOURCES) {
    for (const t of r.tags) mapa.set(t, (mapa.get(t) ?? 0) + 1);
  }
  return [...mapa.entries()]
    .map(([tag, total]) => ({ tag, total }))
    .sort((a, b) => b.total - a.total || a.tag.localeCompare(b.tag, "pt-BR"));
})();

