/* ---------------------------------------------------------------
   JailbreakDN — fonte única de verdade para todos os recursos.

   REGRAS DESTE ARQUIVO (mantidas à risca):

   1. Toda URL é reproduzida VERBATIM do briefing, incluindo
      parâmetros de indicação, convite e playlist. Nada é encurtado,
      normalizado ou reescrito.

   2. `verificado: true` só existe quando a página foi realmente
      consultada e o texto descreve o que foi visto. Os recursos
      identificados apenas pela URL fornecida entram como
      `verificado: false` com uma descrição que declara isso.

   3. `risco` nunca é atribuído sem motivo concreto. `high` exige um
      aviso que explique o motivo. Nenhum link é declarado malicioso.

   4. A organização é por `subcategoriaId` (ver data/categorias.ts). O
      grupo e o nome da categoria são sempre derivados dela: não existe
      campo duplicado que possa divergir.

   5. `disponibilidade` segue data/disponibilidade.ts. O padrão é
      "nao-verificado": só muda quando há evidência registrada. Preço e
      cota nunca são estimados.

   6. `adicionadoEm` é a data em que o recurso entrou neste catálogo
      (não a data de criação do site de destino).
   --------------------------------------------------------------- */

import type { Disponibilidade } from "./disponibilidade";

export type RiskLevel = "none" | "caution" | "high";

export type TipoId =
  | "site"
  | "api"
  | "ferramenta"
  | "repositorio"
  | "video"
  | "download"
  | "artigo"
  | "prompt";

export interface Resource {
  id: string;
  nome: string;
  url: string;
  /** Subcategoria do diretório; define grupo e categoria. */
  subcategoriaId: string;
  /** Classificação de acesso; ver data/disponibilidade.ts. */
  disponibilidade: Disponibilidade;
  /** Etiqueta curta do tipo de coisa ("Chatbot", "VPN"…). */
  subcategoria: string;
  origem: string;
  descricao: string;
  tipo: TipoId;
  tags: string[];
  /** true somente se a página foi consultada ao catalogar. */
  verificado: boolean;
  /** true = exige conta; false = não exige; "desconhecido" = não conferido. */
  conta?: boolean | "desconhecido";
  preco?: string;
  risco: RiskLevel;
  /** Obrigatório quando risco = "high". */
  avisos?: string[];
  /** ISO date (YYYY-MM-DD) — entrada no catálogo, não no site de destino. */
  adicionadoEm: string;
  /** Recurso servido pelo próprio site (prompts), não um site externo. */
  interno?: boolean;
  /** Para prompts: id em src/data/prompts.js. */
  promptId?: number;
}

